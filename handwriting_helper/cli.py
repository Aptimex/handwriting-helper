'''Command line interface: text in, G-code (or SVG) out.'''

import argparse
import sys
from pathlib import Path

from . import __version__
from .strokes import Document, MODEL_CHAR_ADVANCE, paragraphs
from .layout import (
    DEFAULT_LINE_PITCH_RATIO, LayoutError, layout, parse_page, resolve_scale, text_width_mm)
from .gcode_out import (
    BedLimitError, ProfileError, bed_sections, describe_shift, load_profile, reachable_area,
    write_gcode)
from .svg_out import write_svg

GCODE_SUFFIXES = {".gcode", ".gco", ".g", ".nc", ".ngc"}


def build_parser():
    p = argparse.ArgumentParser(
        prog="handwrite.py",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description="Generate plotter G-code that mimics human handwriting.",
        epilog="""examples:
  ./handwrite.py "Hello world" -o output/hello.gcode
  ./handwrite.py --file letter.txt -o output/letter.gcode --profile ender3
  ./handwrite.py --file letter.txt --save-strokes output/letter.strokes.json
  ./handwrite.py --strokes output/letter.strokes.json -o output/letter.svg --smooth

The text is generated by the offline copy of calligrapher.ai in website/, driven in headless
Chromium. Nothing is sent anywhere.""")

    src = p.add_argument_group("input")
    src.add_argument("text", nargs="?", help="text to write")
    src.add_argument("--file", "-f", metavar="PATH",
                     help="read the text from a file ('-' for stdin)")
    src.add_argument("--strokes", metavar="PATH",
                     help="reuse a saved strokes file instead of generating again")
    src.add_argument("--wrap", default="fit", metavar="N",
                     help="line length: 'fit' fills the width between the margins, a number "
                          "asks for lines of about N characters (default: %(default)s)")
    src.add_argument("--keep-breaks", action="store_true",
                     help="honour the line breaks in the input instead of reflowing each "
                          "paragraph to the page width")

    gen = p.add_argument_group("generation")
    gen.add_argument("--style", default="random", metavar="N",
                     help="handwriting style, 0-79, or 'random' (default: %(default)s). "
                          "One style is used for the whole document")
    gen.add_argument("--bias", type=float, default=0.75, metavar="F",
                     help="legibility, 0.15 (loose) to 2.5 (neat) (default: %(default)s)")
    gen.add_argument("--seed", type=int, metavar="N",
                     help="seed the sampler so the output is reproducible; without one, a "
                          "seed is chosen and reported")
    gen.add_argument("--tries", type=int, default=3, metavar="N",
                     help="re-sample a line up to N times if the model gets stuck "
                          "(default: %(default)s)")
    gen.add_argument("--headed", action="store_true",
                     help="show the browser window (for debugging)")

    lay = p.add_argument_group("layout")
    lay.add_argument("--x-height-mm", type=float, default=3.0, metavar="MM",
                     help="height of an x-height letter such as 'n' (default: %(default)s)")
    lay.add_argument("--scale", type=float, metavar="MM",
                     help="set millimetres per model unit directly, ignoring --x-height-mm")
    lay.add_argument("--line-pitch", type=float, metavar="MM",
                     help="baseline to baseline distance (default: {:g} x the "
                          "x-height)".format(DEFAULT_LINE_PITCH_RATIO))
    lay.add_argument("--page", default="a4", metavar="SPEC",
                     help="a3/a4/a5/a6/letter/legal, WxH in mm, or 'fit' for the area of the "
                          "--profile's bed the pen can reach, so any sheet that covers it "
                          "works; margins are then measured from the edges of that area "
                          "(default: %(default)s)")
    lay.add_argument("--margin", default="20", metavar="MM",
                     help="page margin: one value, 'H,V', or 'L,T,R,B' (default: %(default)s)")
    lay.add_argument("--align", default="left", choices=("left", "center", "right"),
                     help="horizontal alignment (default: %(default)s)")

    out = p.add_argument_group("output")
    out.add_argument("--outfile", "-o", default="output/output.gcode", metavar="PATH",
                     help="output path; the format follows the extension. A text that runs "
                          "to several pages is written as NAME-p1, NAME-p2, ...; G-code for a "
                          "page taller than the bed is cut into parts NAME-p1a, NAME-p1b, ... "
                          "(default: %(default)s)")
    out.add_argument("--format", choices=("auto", "gcode", "svg"), default="auto",
                     help="override the format implied by the extension")
    out.add_argument("--save-strokes", metavar="PATH",
                     help="also save the generated strokes, so layout can be re-run without "
                          "generating again")
    out.add_argument("--preview", metavar="PATH",
                     help="also write an SVG preview alongside the G-code")
    out.add_argument("--profile", default=None, metavar="NAME",
                     help="printer profile: a .toml path, or a name from profiles/")
    out.add_argument("--smooth", "-s", action="store_true",
                     help="fit cubic beziers to the strokes; looks better at large sizes")
    out.add_argument("--fit-error", type=float, default=1.0, metavar="F",
                     help="curve fitting tolerance for --smooth, in model units "
                          "(default: %(default)s)")
    out.add_argument("--simplify-tol", type=float, default=0.0, metavar="MM",
                     help="drop points that lie within this distance of the line they span; "
                          "0.05 typically halves the file for no visible change")
    out.add_argument("--pen-width", type=float, default=0.4, metavar="MM",
                     help="stroke width used for SVG output only (default: %(default)s)")
    out.add_argument("--svg-background", action="store_true",
                     help="give SVG output a white background, so black ink stays visible "
                          "in a dark viewer")
    out.add_argument("--dry-run-z", type=float, metavar="MM",
                     help="raise both pen heights by this much, so the motion can be watched "
                          "without the pen touching the paper")
    out.add_argument("--quiet", "-q", action="store_true", help="only report problems")
    p.add_argument("--version", action="version", version="handwriting-helper " + __version__)
    return p


def _read_text(args):
    if args.file:
        if args.file == "-":
            return sys.stdin.read()
        return Path(args.file).read_text(encoding="utf-8")
    return args.text


def _parse_margin(spec):
    values = [float(v) for v in str(spec).replace(" ", "").split(",") if v != ""]
    if len(values) == 1:
        return values[0]
    if len(values) in (2, 4):
        return values
    raise LayoutError("--margin takes one, two or four numbers (got {!r})".format(spec))


def _resolve_page(args, profile):
    '''--page as (width, height) in mm, taking 'fit' from the profile's bed.'''
    if str(args.page).strip().lower() != "fit":
        return parse_page(args.page)
    if not profile["bed"]:
        raise SystemExit("--page fit sizes the page to the printer's bed, so it needs a "
                         "--profile that declares one")
    try:
        return reachable_area(profile)
    except ProfileError as exc:
        raise SystemExit("profile error: {}".format(exc))


def _line_width_units(args, page, wrap, x_height_units, advance_units):
    '''
    How wide a line may be, in model units: the space between the margins at the requested
    size, or about `wrap` characters of this style.

    The generator breaks lines against this by measuring real ink, so it is a hard limit
    rather than an estimate.
    '''
    if wrap == "fit":
        width_mm = text_width_mm(page, _parse_margin(args.margin))
        mm_per_unit, _ = resolve_scale(x_height_units, args.x_height_mm, args.scale)
        return width_mm / mm_per_unit
    return wrap * (advance_units or MODEL_CHAR_ADVANCE)


def _numbered(path, index, total, part=0, parts=1):
    '''
    output.gcode -> output-p2.gcode, when there is more than one page, and
    output-p2a.gcode, output-p2b.gcode, ... when a page is cut into bed-sized parts.
    '''
    if total == 1 and parts == 1:
        return Path(path)
    path = Path(path)
    letter = "abcdefghijklmnopqrstuvwxyz"[part] if parts > 1 else ""
    return path.with_name("{}-p{}{}{}".format(path.stem, index + 1, letter, path.suffix))


def _resolve_format(args):
    if args.format != "auto":
        return args.format
    suffix = Path(args.outfile).suffix.lower()
    if suffix == ".svg":
        return "svg"
    if suffix in GCODE_SUFFIXES:
        return "gcode"
    raise SystemExit(
        "cannot tell the output format from {!r}; pass --format gcode or --format svg".format(
            args.outfile))


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.strokes and (args.text or args.file):
        parser.error("--strokes replaces the text input; don't pass both")
    if not args.strokes and not args.text and not args.file:
        parser.error("give some text, --file PATH, or --strokes PATH")
    wrap = str(args.wrap).strip().lower()
    if wrap != "fit":
        try:
            wrap = int(wrap)
        except ValueError:
            parser.error("--wrap must be a number or 'fit'")
        if wrap < 1:
            parser.error("--wrap must be at least 1")

    style = None
    if str(args.style).lower() not in ("random", "-", "none"):
        try:
            style = int(args.style)
        except ValueError:
            parser.error("--style must be a number 0-79 or 'random'")

    log = (lambda *a: None) if args.quiet else (
        lambda *a: print(*a, file=sys.stderr, flush=True))

    # --- profile and page ------------------------------------------------------------
    # Both are settled before generating: the page width decides where lines break, and
    # --page fit takes the page from the profile's bed.
    try:
        profile = load_profile(args.profile)
        page = _resolve_page(args, profile)
    except ProfileError as exc:
        raise SystemExit("profile error: {}".format(exc))
    except LayoutError as exc:
        raise SystemExit("layout failed: {}".format(exc))
    if str(args.page).strip().lower() == "fit":
        log("page fit: {:g} x {:g} mm, the part of {}'s bed the pen can reach".format(
            page[0], page[1], profile["name"]))

    # --- strokes -------------------------------------------------------------------
    if args.strokes:
        document = Document.from_json(Path(args.strokes).read_text(encoding="utf-8"))
        log("loaded {} lines from {}".format(len(document.lines), args.strokes))
    else:
        from .generate import Generator, GenerationError, warn_unsupported

        text = _read_text(args)
        if not text or not text.strip():
            raise SystemExit("no text to write")
        paras = paragraphs(text, keep_breaks=args.keep_breaks)
        if not paras:
            raise SystemExit("no text to write")

        def progress(line):
            note = "  [ran out of steps]" if line.truncated else ""
            log("  {!r} -> {} points{}".format(line.text, line.point_count(), note))

        try:
            with Generator(style=style, bias=args.bias, seed=args.seed, tries=args.tries,
                           headless=not args.headed) as gen:
                warn_unsupported(gen, paras)
                width = _line_width_units(args, page, wrap, gen.x_height_units,
                                          gen.char_advance_units)
                log("generating {} paragraph(s), style {}, seed {}, lines up to {:.0f} "
                    "model units".format(sum(p is not None for p in paras), gen.style,
                                         gen.seed, width))
                document = gen.document(paras, width, progress=progress)
        except (GenerationError, LayoutError) as exc:
            raise SystemExit("generation failed: {}".format(exc))

        truncated = [l.text for l in document.lines if l.truncated]
        if truncated:
            log("warning: {} line(s) ran out of sampling steps even after {} tries and may "
                "be short: {}".format(len(truncated), args.tries,
                                      ", ".join(repr(t) for t in truncated)))

    if args.save_strokes:
        target = Path(args.save_strokes)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(document.to_json(), encoding="utf-8")
        log("wrote {}".format(target))

    # --- layout --------------------------------------------------------------------
    try:
        pages = layout(document, page=page, margin_mm=_parse_margin(args.margin),
                       x_height_mm=args.x_height_mm, line_pitch_mm=args.line_pitch,
                       align=args.align, mm_per_unit=args.scale)
    except LayoutError as exc:
        raise SystemExit("layout failed: {}".format(exc))

    first = pages[0]
    log("{} page(s) of {:.0f} x {:.0f} mm, x-height {:.2f} mm, line pitch {:.2f} mm".format(
        len(pages), first.width_mm, first.height_mm, first.x_height_mm,
        first.line_pitch_mm))

    # --- output --------------------------------------------------------------------
    fmt = _resolve_format(args)
    svg_options = dict(smooth=args.smooth, fit_error=args.fit_error,
                       pen_width_mm=args.pen_width, simplify_tol=args.simplify_tol,
                       background=args.svg_background)

    if fmt == "svg":
        for index, page in enumerate(pages):
            target = _numbered(args.outfile, index, len(pages))
            count = write_svg(page, target, **svg_options)
            log("wrote {} ({} paths)".format(target, count))
        return 0

    if args.profile is None:
        log("no --profile given, using built-in defaults: pen down Z{:g}, up Z{:g}. "
            "Check these before running.".format(profile["pen_down_z"], profile["pen_up_z"]))

    if args.dry_run_z:
        profile["pen_down_z"] += args.dry_run_z
        profile["pen_up_z"] += args.dry_run_z
        profile["safe_z"] = max(profile["safe_z"], profile["pen_up_z"] + 5)
        log("dry run: pen heights raised by {:g} mm (down Z{:g}, up Z{:g})".format(
            args.dry_run_z, profile["pen_down_z"], profile["pen_up_z"]))

    header = "text: {}".format(" / ".join(l.text for l in document.lines if l.text)[:200])
    for index, page in enumerate(pages):
        sections = bed_sections(page, profile)
        if len(sections) > 26:
            raise SystemExit("refusing to write G-code: the page would need {} bed-sized "
                             "parts".format(len(sections)))
        if len(sections) > 1:
            log("page {} is taller than the bed's Y travel; writing it in {} parts".format(
                index + 1, len(sections)))
        for part, section in enumerate(sections):
            target = _numbered(args.outfile, index, len(pages), part, len(sections))
            page_header = header
            if len(pages) > 1:
                page_header += "\npage {} of {}".format(index + 1, len(pages))
            if len(sections) > 1:
                page_header += "\npart {} of {} of the page".format(
                    "abcdefghijklmnopqrstuvwxyz"[part], len(sections))
            try:
                stats = write_gcode(page, target, profile, smooth=args.smooth,
                                    fit_error=args.fit_error, simplify_tol=args.simplify_tol,
                                    header_comment=page_header, section=section)
            except BedLimitError as exc:
                raise SystemExit("refusing to write G-code: {}".format(exc))
            log("wrote {}: {} strokes, {} points, {:.0f} mm drawn, ~{:.1f} min".format(
                target, stats["strokes"], stats["points"], stats["draw_mm"],
                stats["minutes"]))
            placement = describe_shift(section, profile)
            if placement:
                log("  before running it, " + placement)
            elif len(sections) > 1:
                log("  paper in its usual place")

        if args.preview:
            preview = _numbered(args.preview, index, len(pages))
            write_svg(page, preview, **svg_options)
            log("wrote {}".format(preview))
    return 0
